import { useState } from "react";
import { useSearchParams } from "react-router-dom";
import { RichText } from "../components/RichText";
import { Card, ErrorBox, InvestigationLink, Loading, PageHeader, PillarBadges } from "../components/ui";
import { useApi } from "../hooks/useApi";
import { api } from "../lib/api";
import { formatRange } from "../lib/format";
import type { CompareResponse, Investigation } from "../lib/types";

const MAX = 4;
const ROWS: { label: string; value: (i: Investigation) => string }[] = [
  { label: "Group", value: (i) => i.group },
  { label: "Hardware", value: (i) => i.psi.hardware || "—" },
  { label: "Fuels / materials", value: (i) => i.fuels.join(", ") },
  { label: "Samples", value: (i) => i.sample },
  { label: "Tests", value: (i) => String(i.stats.n_tests || "—") },
  { label: "Oxygen", value: (i) => formatRange(i.stats.o2_pct, " %") },
  { label: "Pressure", value: (i) => formatRange(i.stats.pressure_psi, " psi") },
  { label: "Air flow", value: (i) => formatRange(i.stats.flow_cm_s, " cm/s", 0) },
  { label: "Varied", value: (i) => i.stats.varied.join(", ") || "—" },
  { label: "Held the same", value: (i) => i.stats.fixed.join(", ") || "—" },
  { label: "Measurements", value: (i) => i.measurements.join(", ") },
];

export function Compare() {
  const [params, setParams] = useSearchParams();
  const selected = (params.get("ids") ?? "PSI-26,PSI-25").split(",").filter(Boolean);
  const invs = useApi(api.investigations, []);
  const [result, setResult] = useState<CompareResponse | null>(null);
  const [state, setState] = useState<{ loading: boolean; error: string | null }>({ loading: false, error: null });

  const toggle = (id: string) => {
    const next = selected.includes(id) ? selected.filter((s) => s !== id) : [...selected, id].slice(-MAX);
    setParams({ ids: next.join(",") });
    setResult(null);
  };
  const run = () => {
    setState({ loading: true, error: null });
    api.compare(selected).then(setResult).then(() => setState({ loading: false, error: null }))
      .catch((e: Error) => setState({ loading: false, error: e.message }));
  };

  return (
    <div>
      <PageHeader title="Compare investigations" subtitle="Pick 2–4 investigations to line up their fuels, conditions and measurements, and have SPARK explain what they share and how they differ." />
      {invs.error && <ErrorBox message={invs.error} />}
      <div className="mb-4 flex flex-wrap gap-1.5">
        {invs.data?.map((inv) => (
          <button key={inv.id} onClick={() => toggle(inv.id)}
            className={`rounded-full px-3 py-1 text-xs transition ${selected.includes(inv.id) ? "bg-orange-500 text-white" : "bg-white/5 text-slate-300 hover:bg-white/10"}`}>
            {inv.short}
          </button>
        ))}
      </div>
      <button disabled={selected.length < 2 || state.loading} onClick={run}
        className="mb-6 rounded-xl bg-orange-500 px-4 py-2 text-sm font-medium text-white hover:bg-orange-400 disabled:opacity-40">
        Compare {selected.length} investigations
      </button>
      {state.loading && <Loading label="Lining up the data and asking SPARK…" />}
      {state.error && <ErrorBox message={state.error} />}
      {result && <CompareResult result={result} />}
    </div>
  );
}

function CompareResult({ result }: { result: CompareResponse }) {
  const items = result.investigations;
  return (
    <div className="space-y-6">
      <Card>
        <h2 className="mb-2 font-display text-lg font-semibold text-white">SPARK's reading</h2>
        {result.narrative ? <RichText text={result.narrative} /> : <p className="text-sm text-slate-400">The AI service is busy right now; the side-by-side table below is computed directly from PSI data.</p>}
        {result.model && <p className="mt-3 text-xs text-slate-500">Generated by {result.model} from PSI records. Check against the sources.</p>}
      </Card>
      <Card className="overflow-x-auto">
        <table className="w-full min-w-[640px] text-sm">
          <thead>
            <tr>
              <th className="w-36" />
              {items.map((i) => (
                <th key={i.id} className="pb-3 text-left align-top">
                  <InvestigationLink id={i.id} label={i.short} />
                  <div className="mt-1 font-normal"><PillarBadges pillars={i.pillars} /></div>
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {ROWS.map((row) => (
              <tr key={row.label} className="border-t border-white/5 align-top">
                <td className="py-2 pr-3 text-xs uppercase tracking-wide text-slate-500">{row.label}</td>
                {items.map((i) => <td key={i.id} className="py-2 pr-4 text-slate-300">{row.value(i)}</td>)}
              </tr>
            ))}
          </tbody>
        </table>
      </Card>
    </div>
  );
}
