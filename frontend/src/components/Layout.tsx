import { useEffect, useState } from "react";
import { Link, NavLink, Outlet, useLocation } from "react-router-dom";

const NAV = [
  { to: "/", label: "Missions" },
  { to: "/conditions", label: "Test Conditions" },
  { to: "/investigations", label: "Investigations" },
  { to: "/compare", label: "Compare" },
  { to: "/ask", label: "Ask SPARK" },
  { to: "/insights", label: "Insights" },
];

function Wordmark() {
  return (
    <Link to="/" className="flex items-center gap-3" aria-label="SPARK home">
      <span className="relative grid h-9 w-9 place-items-center rounded-full bg-accent">
        <span className="h-3.5 w-3.5 rounded-full border-2 border-white" />
      </span>
      <span className="leading-none">
        <span className="block text-lg font-extrabold tracking-[0.12em] text-white">SPARK</span>
        <span className="block font-mono text-[0.62rem] uppercase tracking-[0.18em] text-white/60">Space Fire Atlas</span>
      </span>
    </Link>
  );
}

function NavItems({ onClick }: { onClick?: () => void }) {
  return NAV.map((item) => (
    <NavLink
      key={item.to}
      to={item.to}
      end={item.to === "/"}
      onClick={onClick}
      className={({ isActive }) =>
        `relative block px-3 py-2 text-sm font-semibold transition md:py-6 ${isActive ? "text-white" : "text-white/65 hover:text-white"}
         ${isActive ? "md:after:absolute md:after:inset-x-3 md:after:bottom-0 md:after:h-[3px] md:after:bg-accent" : ""}`
      }
    >
      {item.label}
    </NavLink>
  ));
}

export function Layout() {
  const [open, setOpen] = useState(false);
  const { pathname } = useLocation();
  useEffect(() => {
    window.scrollTo(0, 0);
  }, [pathname]);

  return (
    <div className="flex min-h-screen flex-col">
      <div className="bg-night-2 text-white/60">
        <div className="mx-auto max-w-7xl px-4 py-1.5 font-mono text-[0.65rem] uppercase tracking-[0.16em]">
          NASA Space Apps Challenge 2026 · Built on NASA Physical Sciences Informatics open data
        </div>
      </div>
      <header className="sticky top-0 z-30 border-b border-night-line bg-night">
        <div className="mx-auto flex max-w-7xl items-center justify-between gap-6 px-4 py-3 md:py-0">
          <Wordmark />
          <nav className="hidden items-center md:flex"><NavItems /></nav>
          <button className="text-white md:hidden" onClick={() => setOpen(!open)} aria-label="Toggle menu" aria-expanded={open}>
            <span className="font-mono text-xs uppercase tracking-widest">{open ? "Close" : "Menu"}</span>
          </button>
        </div>
        {open && <nav className="border-t border-night-line px-4 pb-3 md:hidden"><NavItems onClick={() => setOpen(false)} /></nav>}
      </header>

      <main className="flex-1"><Outlet /></main>

      <footer className="bg-night text-white/70">
        <div className="mx-auto grid max-w-7xl gap-10 px-4 py-14 md:grid-cols-[1.4fr_1fr_1fr]">
          <div>
            <Wordmark />
            <p className="mt-4 max-w-md text-sm leading-relaxed">
              SPARK summarizes, ranks and interprets NASA microgravity combustion research to support fire safety for
              spacecraft, space stations, lunar and Martian bases, and pressurized rovers.
            </p>
          </div>
          <div>
            <div className="font-mono text-xs uppercase tracking-[0.16em] text-white">Data</div>
            <ul className="mt-3 space-y-2 text-sm">
              <li><a className="hover:text-white" href="https://psi.nasa.gov/physci/repo/search?q=combustion" target="_blank" rel="noreferrer">NASA PSI Data Repository ↗</a></li>
              <li><a className="hover:text-white" href="https://www.nasa.gov/glenn/glenn-expertise-space-exploration/physical-sciences-program/combustion-science/" target="_blank" rel="noreferrer">NASA Combustion Science ↗</a></li>
              <li><a className="hover:text-white" href="https://www.nasa.gov/missions/station/a-researchers-guide-to-combustion-science/" target="_blank" rel="noreferrer">Researcher's Guide to ISS Combustion ↗</a></li>
            </ul>
          </div>
          <div>
            <div className="font-mono text-xs uppercase tracking-[0.16em] text-white">About this site</div>
            <p className="mt-3 text-sm leading-relaxed">
              PSI data are CC0; cite each investigation by its DOI. Summaries and answers marked "AI" are generated by Google
              Gemini from PSI evidence and may contain errors. Images: NASA PSI (public domain). An independent Space Apps
              project, not endorsed by NASA.
            </p>
          </div>
        </div>
      </footer>
    </div>
  );
}
